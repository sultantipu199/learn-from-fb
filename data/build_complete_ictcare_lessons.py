def main():
    with open('data/lessons_data.json', 'r', encoding='utf-8') as f:
        lessons = json.load(f)

    existing_urls = set(l['video_url'] for l in lessons)

    added_count = 0
    for nl in ictcare_new_lessons:
        if nl['video_url'] not in existing_urls:
            lessons.append(nl)
            added_count += 1
            print(f"Added Lesson {nl['lesson_number']}: {nl['title']}")
        else:
            for i, l in enumerate(lessons):
                if l['video_url'] == nl['video_url']:
                    lessons[i] = nl
                    print(f"Updated Lesson {nl['lesson_number']}: {nl['title']}")

    # Re-align sequentially
    for idx, l in enumerate(lessons, 1):
        l['lesson_id'] = idx
        l['lesson_number'] = f"{idx:02d}"

    print(f"\nTotal lessons after adding: {len(lessons)} (Added {added_count} new lessons)")

    with open('data/lessons_data.json', 'w', encoding='utf-8') as f:
        json.dump(lessons, f, indent=2, ensure_ascii=False)
    print("Saved data/lessons_data.json successfully.")

    with open('web_viewer/lessons_data.json', 'w', encoding='utf-8') as f:
        json.dump(lessons, f, indent=2, ensure_ascii=False)
    print("Saved web_viewer/lessons_data.json successfully.")

if __name__ == '__main__':
    main()
